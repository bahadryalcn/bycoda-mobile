export function readonlyRequest(method: string, params: Record<string, unknown>): boolean {
  return (
    READ_METHODS.has(method) ||
    (method === "social.request" &&
      typeof params.action === "string" &&
      READ_SOCIAL_ACTIONS.has(params.action))
  );
}
