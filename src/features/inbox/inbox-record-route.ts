import type { Href } from "expo-router";
import type { RemoteInboxItem, RemoteInboxTarget } from "../../../../src/features/inbox/model/remoteInbox";
import { REMOTE_INBOX_PROVIDERS } from "../../../../src/features/inbox/model/remoteInbox";
import type { InboxOrigin } from "./provider-protocol";
import type { JiraBoardSnapshot } from "./jira-board-model";

/**
 * Record pages are pushed routes. Their params carry identity only (provider, kind, number,
 * repository, project path and the tracker id/key) plus the computer and project that own it;
 * title, state, labels and URL are always read from the phone's own list caches, never the link.
 */
export type InboxRecordTarget = RemoteInboxTarget;
export type InboxRecordParams = {
  machineId: string; projectId: string; provider: string; kind: string; number: string;
  repo: string; projectPath: string; id?: string; identifier?: string; boardSnapshot?: string;
};

const text = (value: unknown, maximum: number) => typeof value === "string" && value.length <= maximum && !value.includes("\0") ? value : null;

export function readInboxRecordRoute(params: Record<string, unknown>): InboxRecordTarget | null {
  const provider = params.provider, kind = params.kind;
  if (typeof provider !== "string" || !(REMOTE_INBOX_PROVIDERS as readonly string[]).includes(provider)) return null;
  if (provider === "linear" ? kind !== "linear" : provider === "jira" ? kind !== "jira" : kind !== "issue" && kind !== "pr") return null;
  const number = Number(params.number);
  if (typeof params.number !== "string" || !Number.isSafeInteger(number) || number < 0 || String(number) !== params.number) return null;
  const repo = text(params.repo ?? "", 1_000), projectPath = text(params.projectPath ?? "", 1_024);
  if (repo === null || projectPath === null) return null;
  const id = params.id === undefined || params.id === "" ? undefined : text(params.id, 200);
  const identifier = params.identifier === undefined || params.identifier === "" ? undefined : text(params.identifier, 200);
  if (id === null || identifier === null) return null;
  if (provider === "linear" && !id) return null;
  if (provider === "jira" && !identifier) return null;
  if (provider !== "linear" && provider !== "jira" && (number < 1 || !repo)) return null;
  return { provider: provider as InboxRecordTarget["provider"], kind: kind as InboxRecordTarget["kind"], number, repo, projectPath, ...(id ? { id } : {}), ...(identifier ? { identifier } : {}) };
}

/** Identity match only. */
export function matchInboxRecord(items: readonly RemoteInboxItem[] | undefined, target: InboxRecordTarget): RemoteInboxItem | null {
  return items?.find((item) => item.provider === target.provider && item.kind === target.kind && item.number === target.number &&
    item.repo === target.repo && item.projectPath === target.projectPath && (item.id ?? undefined) === target.id &&
    (item.identifier ?? undefined) === target.identifier) ?? null;
}

const recordKey = (machineId: string, projectId: string | null, target: InboxRecordTarget) =>
  JSON.stringify([machineId, projectId, target.provider, target.kind, target.number, target.repo, target.projectPath, target.id ?? null, target.identifier ?? null]);
/**
 * Rows opened from a list that is not a provider list read (a Jira board page): the phone hands
 * the tapped row to the pushed page in memory. Bounded; the oldest entries go first.
 */
const handoff = new Map<string, RemoteInboxItem>();
const snapshots = new Map<string, JiraBoardSnapshot>();
function remember<T>(map: Map<string, T>, key: string, value: T) {
  map.delete(key); map.set(key, value);
  while (map.size > 40) map.delete(map.keys().next().value!);
}
export function rememberInboxRecord(origin: InboxOrigin, item: RemoteInboxItem) {
  remember(handoff, recordKey(origin.machineId, origin.projectId, item), item);
}
export function recallInboxRecord(machineId: string, projectId: string | null, target: InboxRecordTarget): RemoteInboxItem | null {
  return handoff.get(recordKey(machineId, projectId, target)) ?? null;
}
/** The board page a Jira issue was opened from: its status and move actions need that snapshot. */
export function rememberJiraSnapshot(origin: InboxOrigin, snapshot: JiraBoardSnapshot) {
  remember(snapshots, JSON.stringify([origin.machineId, origin.projectId, snapshot.snapshotId]), snapshot);
}
export function recallJiraSnapshot(machineId: string, projectId: string | null, snapshotId: string | undefined): JiraBoardSnapshot | null {
  return snapshotId ? snapshots.get(JSON.stringify([machineId, projectId, snapshotId])) ?? null : null;
}

/**
 * The Inbox's pushed pages under `app/inbox/`. Typed routes are generated by the dev server, which
 * may not have seen these pages yet, so their links are asserted here, in one place.
 */
export function inboxPage(href: { pathname: `/inbox/${string}`; params: Record<string, string | undefined> }): Href {
  return href as unknown as Href;
}
/** GitHub pull requests keep their deep-linkable route; every other record opens the shared record page. */
export function inboxRecordHref(item: RemoteInboxItem, origin: InboxOrigin, options?: { boardSnapshot?: string }): Href {
  if (item.provider === "github" && item.kind === "pr" && !options?.boardSnapshot)
    return { pathname: "/pull-requests/[id]", params: { id: String(item.number), repo: item.repo, projectPath: item.projectPath,
      machineId: origin.machineId, projectId: origin.projectId ?? "" } };
  return inboxPage({ pathname: "/inbox/record", params: inboxRecordParams(item, origin, options) });
}
export function inboxRecordParams(item: RemoteInboxTarget, origin: InboxOrigin, options?: { boardSnapshot?: string }): InboxRecordParams {
  return {
    machineId: origin.machineId, projectId: origin.projectId ?? "", provider: item.provider, kind: item.kind, number: String(item.number),
    repo: item.repo, projectPath: item.projectPath, ...(item.id ? { id: item.id } : {}), ...(item.identifier ? { identifier: item.identifier } : {}),
    ...(options?.boardSnapshot ? { boardSnapshot: options.boardSnapshot } : {}),
  };
}
/** The review and diff pages share the record's identity params. */
export function inboxReviewHref(item: RemoteInboxTarget, origin: InboxOrigin): Href {
  return inboxPage({ pathname: "/inbox/review", params: inboxRecordParams(item, origin) });
}
export function inboxReviewFileHref(item: RemoteInboxTarget, origin: InboxOrigin, path: string, anchor?: { side: "LEFT" | "RIGHT"; line: number }): Href {
  return inboxPage({ pathname: "/inbox/review-file", params: { ...inboxRecordParams(item, origin), path,
    ...(anchor ? { side: anchor.side, line: String(anchor.line) } : {}) } });
}
