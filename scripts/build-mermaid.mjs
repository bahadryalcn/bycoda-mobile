import { build } from "esbuild";
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const entry = require.resolve("mermaid");
const result = await build({ stdin: { contents: 'import mermaid from "mermaid"; window.byCodaMermaid = mermaid;', resolveDir: root }, bundle: true, format: "iife", platform: "browser", target: ["chrome100", "safari16"], minify: true, write: false, legalComments: "inline" });
const assets = resolve(root, "assets");
await mkdir(assets, { recursive: true });
await writeFile(resolve(assets, "mermaid-runtime.js"), `// Generated by scripts/build-mermaid.mjs; Mermaid 11.16.1, MIT.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);
await writeFile(resolve(assets, "mermaid-runtime.d.ts"), "declare const runtime: string; export default runtime;\n");
await writeFile(resolve(assets, "mermaid-LICENSE.txt"), await readFile(resolve(dirname(entry), "../LICENSE")));
process.stdout.write(`Bundled offline Mermaid: ${result.outputFiles[0].contents.length} bytes\n`);
