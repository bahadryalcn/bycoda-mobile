import { build } from "esbuild";
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const xterm = dirname(require.resolve("@xterm/xterm/package.json"));
const fit = dirname(require.resolve("@xterm/addon-fit/package.json"));
const versions = [
  JSON.parse(await readFile(resolve(xterm, "package.json"), "utf8")).version,
  JSON.parse(await readFile(resolve(fit, "package.json"), "utf8")).version,
];
if (versions.join(",") !== "6.0.0,0.11.0")
  throw new Error("Review offline terminal runtime versions before regeneration");
const result = await build({
  stdin: {
    contents:
      'import {Terminal} from "@xterm/xterm"; import {FitAddon} from "@xterm/addon-fit"; window.BycodaTerminalRuntime={Terminal,FitAddon};',
    resolveDir: root,
  },
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["chrome100", "safari16"],
  minify: true,
  write: false,
  legalComments: "inline",
});
const css = await readFile(resolve(xterm, "css/xterm.css"), "utf8");
const assets = resolve(root, "assets");
await mkdir(assets, { recursive: true });
const files = {
  "terminal-runtime.js": `// Generated by scripts/build-terminal.mjs; xterm ${versions[0]}, fit ${versions[1]}. MIT.\nexport const runtime=${JSON.stringify(result.outputFiles[0].text)};\nexport const terminalCss=${JSON.stringify(css)};\n`,
  "terminal-runtime.d.ts":
    "export declare const runtime:string;\nexport declare const terminalCss:string;\n",
  "terminal-LICENSE.txt": `xterm ${versions[0]}\n${await readFile(resolve(xterm, "LICENSE"), "utf8")}\naddon-fit ${versions[1]}\n${await readFile(resolve(fit, "LICENSE"), "utf8")}`,
};
for (const [name, content] of Object.entries(files)) {
  const file = resolve(assets, name);
  if (process.argv.includes("--check")) {
    if ((await readFile(file, "utf8")) !== content)
      throw new Error(`Stale generated terminal asset: ${name}`);
  } else await writeFile(file, content);
}
process.stdout.write(
  `Offline terminal ${process.argv.includes("--check") ? "verified" : "generated"}: ${result.outputFiles[0].contents.length} bytes; installed dependencies only\n`,
);
