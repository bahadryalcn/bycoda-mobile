#!/usr/bin/env node
// Copies the public client contract (../packages/account-contracts) into
// src/features/account/contracts and records sha256 hashes in CONTRACT_SOURCE.json.
//
//   node scripts/sync-account-contracts.mjs          copy and write CONTRACT_SOURCE.json
//   node scripts/sync-account-contracts.mjs --check  exit 1 when the copy is stale or edited
//
// Why a copy: this repository is built on its own (EAS uploads only this tree), so a workspace
// or file: link to ../packages cannot be relied on. Source directory: env BYCODA_CONTRACTS_DIR,
// default ../packages/account-contracts. Without a source, --check verifies the copy against the
// manifest. Text is LF-normalized before hashing so Windows and Linux checkouts agree.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const mobileRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.resolve(
  process.env.BYCODA_CONTRACTS_DIR ?? path.join(mobileRoot, "..", "packages", "account-contracts"),
);
const destRoot = path.join(mobileRoot, "src", "features", "account", "contracts");
const manifestPath = path.join(destRoot, "CONTRACT_SOURCE.json");
const check = process.argv.includes("--check");

const sha256 = (text) => createHash("sha256").update(text).digest("hex");
const normalize = (buffer) => buffer.toString("utf8").replace(/\r\n/g, "\n");
const isShipped = (relative) => relative.endsWith(".ts") && !relative.endsWith(".test.ts");

function listFiles(root) {
  const found = [];
  const walk = (directory) => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const full = path.join(directory, entry.name);
      if (entry.isDirectory()) walk(full);
      else found.push(path.relative(root, full).split(path.sep).join("/"));
    }
  };
  if (fs.existsSync(root)) walk(root);
  return found.filter(isShipped).sort();
}

function readTree(root) {
  return new Map(listFiles(root).map((relative) => [relative, normalize(fs.readFileSync(path.join(root, relative)))]));
}

function describeFiles(files) {
  const hashes = {};
  for (const [relative, text] of [...files].sort(([a], [b]) => (a < b ? -1 : 1))) hashes[relative] = sha256(text);
  const overall = sha256(Object.entries(hashes).map(([file, hash]) => `${file}\n${hash}\n`).join(""));
  return { hashes, overall };
}

const fail = (lines) => {
  console.error(lines.join("\n"));
  process.exit(1);
};
const sourceExists = fs.existsSync(path.join(sourceRoot, "src", "index.ts"));
const readManifest = () => (fs.existsSync(manifestPath) ? JSON.parse(fs.readFileSync(manifestPath, "utf8")) : null);

if (check) {
  const actual = readTree(destRoot);
  const recorded = readManifest();
  if (!recorded) fail(["CONTRACT_SOURCE.json is missing. Run: node scripts/sync-account-contracts.mjs"]);
  const problems = [];
  const expected = sourceExists ? readTree(path.join(sourceRoot, "src")) : null;
  const reference = expected ?? new Map(Object.keys(recorded.files).map((file) => [file, null]));
  for (const [relative, text] of reference) {
    if (!actual.has(relative)) problems.push(`missing   ${relative}`);
    else if (text !== null && actual.get(relative) !== text) problems.push(`stale     ${relative}`);
    else if (sha256(actual.get(relative)) !== recorded.files[relative]) problems.push(`modified  ${relative}`);
  }
  for (const relative of actual.keys()) if (!reference.has(relative)) problems.push(`extra     ${relative}`);
  if (problems.length) fail([...problems, "Run: node scripts/sync-account-contracts.mjs"]);
  console.log(`Account contracts match ${expected ? "the source" : "CONTRACT_SOURCE.json"} (${recorded.contractVersion}).`);
} else {
  if (!sourceExists) fail([`Source not found: ${sourceRoot}`, "Set BYCODA_CONTRACTS_DIR to packages/account-contracts."]);
  const files = readTree(path.join(sourceRoot, "src"));
  fs.rmSync(destRoot, { recursive: true, force: true });
  for (const [relative, text] of files) {
    const target = path.join(destRoot, relative);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, text);
  }
  const { hashes, overall } = describeFiles(files);
  const version = /CONTRACT_VERSION\s*=\s*"([^"]+)"/.exec(files.get("version.ts") ?? "")?.[1] ?? "unknown";
  fs.writeFileSync(
    manifestPath,
    `${JSON.stringify(
      {
        note: "Generated by scripts/sync-account-contracts.mjs. Do not edit this folder by hand.",
        source: "packages/account-contracts/src",
        contractVersion: version,
        overallSha256: overall,
        files: hashes,
      },
      null,
      2,
    )}\n`,
  );
  console.log(`Synced ${files.size} files, contract ${version}, sha256 ${overall.slice(0, 12)}.`);
}
