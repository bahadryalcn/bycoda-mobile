import { build } from "esbuild";
import { createRequire } from "node:module";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const require = createRequire(import.meta.url);
const packageRoot = dirname(require.resolve("pdfjs-dist/package.json"));
const resourceGroups = {};
for (const [kind, directory, extension] of [["cMapUrl", "cmaps", ".bcmap"], ["standardFontDataUrl", "standard_fonts", null]]) {
  const group = resourceGroups[kind] = {};
  for (const name of (await readdir(resolve(packageRoot, directory))).sort()) {
    if (name.startsWith("LICENSE") || extension && !name.endsWith(extension)) continue;
    group[name] = (await readFile(resolve(packageRoot, directory, name))).toString("base64");
  }
}
const result = await build({ entryPoints: [resolve(root, "src/ui/pdf-viewer-runtime.js")], bundle: true,
  format: "iife", platform: "browser", target: ["chrome100", "safari16"], minify: true,
  write: false, legalComments: "inline", plugins: [{ name: "offline-pdf-resources", setup(plugin) {
    plugin.onResolve({ filter: /^bycoda:pdf-resources$/ }, () => ({ path: "resources", namespace: "bycoda-pdf" }));
    plugin.onLoad({ filter: /.*/, namespace: "bycoda-pdf" }, () => ({ contents: `export default ${JSON.stringify(resourceGroups)};`, loader: "js" }));
  } }],
});
const assets = resolve(root, "assets");
async function output(name, content) {
  if (process.argv.includes("--check")) {
    if (await readFile(resolve(assets, name), "utf8").catch(() => "") !== content)
      throw new Error(`${name} is stale. Run pnpm pdf:build.`);
  } else {
    await mkdir(assets, { recursive: true });
    await writeFile(resolve(assets, name), content);
  }
}
await output("pdf-runtime.js", `// Generated by scripts/build-pdf.mjs; PDF.js 6.4.299, Apache-2.0. See pdf-LICENSE.txt.\nexport default ${JSON.stringify(result.outputFiles[0].text)};\n`);
await output("pdf-runtime.d.ts", "declare const runtime: string; export default runtime;\n");
const notices = [];
for (const [title, location] of [["PDF.js", "LICENSE"], ["Adobe CMaps", "cmaps/LICENSE"], ["Foxit fonts", "standard_fonts/LICENSE_FOXIT"], ["Liberation fonts", "standard_fonts/LICENSE_LIBERATION"]])
  notices.push(`${title}\n\n${await readFile(resolve(packageRoot, location), "utf8")}`);
await output("pdf-LICENSE.txt", notices.join("\n\n--------------------\n\n"));
process.stdout.write(`Bundled offline PDF.js: ${result.outputFiles[0].contents.length} bytes\n`);
