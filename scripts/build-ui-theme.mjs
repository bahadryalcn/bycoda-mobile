import { createRequire } from "node:module";
import { themeColorRoles } from "../src/ui/theme-color-roles.ts";
import { writeFile, readFile } from "node:fs/promises";
import { PALETTE_IDS, uniwindThemeName, resolveMobilePalette, space, radii, fontSize, lineHeight, metrics } from "../src/ui/tokens.ts";

const require = createRequire(import.meta.url);
const requireUniwind = createRequire(require.resolve("uniwind/package.json"));
const { converter, formatCss } = requireUniwind("culori");
const toOklch = converter("oklch");
function paletteFor(paletteId, mode) {
  return themeColorRoles(resolveMobilePalette(paletteId, mode));
}
const cssColor = (color) => formatCss(toOklch(color));
const declarations = Object.entries(paletteFor("classic", "dark")).map(
  ([name, color]) => `  --color-${name}: ${cssColor(color)};`,
);
for (const [name, value] of Object.entries(space))
  declarations.push(`  --spacing-ui-${name}: ${value}px;`);
for (const [name, value] of Object.entries(radii))
  declarations.push(`  --radius-${name}: ${value}px;`);
declarations.push(
  `  --radius-sm: ${radii.badge}px;`,
  `  --radius-md: ${radii.control}px;`,
  `  --radius-lg: ${radii.card}px;`,
  `  --radius-xl: ${radii.preview}px;`,
  `  --radius-2xl: ${radii.sheet}px;`,
  `  --spacing-control: ${metrics.controlHeight}px;`,
  `  --spacing-touch: ${metrics.touchTarget}px;`,
  `  --spacing-visual: ${metrics.visualControl}px;`,
  `  --spacing-chip: ${metrics.chipHeight}px;`,
  "  --font-sans: system-ui;",
  "  --font-mono: ui-monospace;",
  `  --text-xs: ${fontSize.caption}px;`,
  `  --text-xs--line-height: ${lineHeight.caption}px;`,
  `  --text-sm: ${fontSize.control}px;`,
  `  --text-sm--line-height: ${lineHeight.control}px;`,
  `  --text-base: ${fontSize.body}px;`,
  `  --text-base--line-height: ${lineHeight.body}px;`,
  `  --text-lg: ${fontSize.title}px;`,
  `  --text-lg--line-height: ${lineHeight.title}px;`,
  `  --text-xl: ${fontSize.heading}px;`,
  `  --text-xl--line-height: ${lineHeight.heading}px;`,
  `  --text-2xl: ${fontSize.hero}px;`,
  `  --text-2xl--line-height: ${lineHeight.hero}px;`,
);
for (const [name, value] of Object.entries(fontSize))
  declarations.push(`  --text-ui-${name}: ${value}px;`, `  --text-ui-${name}--line-height: ${lineHeight[name]}px;`);

const shape = { xs: radii.badge, sm: radii.badge, md: radii.control, lg: radii.card, xl: radii.preview, "2xl": radii.sheet, "3xl": radii.sheet };
const themes = PALETTE_IDS.flatMap((paletteId) => ["light", "dark"].map((mode) => ({ name: uniwindThemeName(paletteId, mode), paletteId, mode })));
const extraThemeNames = themes.map((theme) => theme.name).filter((name) => name !== "light" && name !== "dark");
const customVariants = extraThemeNames.map((name) => `@custom-variant ${name} (&:where(.${name}, .${name} *));`).join("\n");
const variants = themes.map(({ name, paletteId, mode }) => `  @variant ${name} {\n${Object.entries(paletteFor(paletteId, mode)).map(([key, value]) => `    --color-${key}: ${cssColor(value)};`).join("\n")}\n${Object.entries(shape).map(([key, value]) => `    --radius-${key}: ${value}px;`).join("\n")}\n  }`).join("\n");
const css = `/* Generated by scripts/build-ui-theme.mjs from ui/tokens.ts. */\n@import "tailwindcss";\n@import "uniwind";\n@import "panelui-native/theme.css";\n@source "./";\n@source "../app";\n@source "../node_modules/panelui-native/src";\n\n${customVariants}\n\n@theme {\n${declarations.join("\n")}\n}\n\n@layer theme {\n  :root {\n${variants}\n  }\n}\n`;
const target = new URL("../src/global.css", import.meta.url);
if (process.argv.includes("--check")) {
  if ((await readFile(target, "utf8")) !== css)
    throw new Error("Shared CSS theme is stale. Run pnpm theme:build.");
  console.log("Shared native and UniWind theme tokens match.");
} else {
  await writeFile(target, css);
  console.log("Shared UniWind theme generated from native tokens.");
}
